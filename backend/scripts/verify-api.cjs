  await admin('PUT', '/api/admin/dia-diem/' + place.id, {...body, ten: body.ten + ' Updated'});
  const updated = (await guest('GET', '/api/dia-diem?danhMuc=' + category.id)).data.content.find(p => p.id === place.id);
