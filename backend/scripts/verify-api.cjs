// Runs only against a deliberately isolated local test server. Never seeds the normal application DB.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.TEST_API_URL || 'http://127.0.0.1:18080';
assert.equal(new URL(base).hostname, '127.0.0.1');
assert.equal(new URL(base).port, '18080');
const checks = [];
function client() {
  let cookie = '', csrf;
  return async function call(method, url, data, expected = 200) {
    if (method !== 'GET' && !csrf) csrf = (await call('GET', '/api/auth/csrf')).data;
    const headers = {Cookie: cookie};
    if (csrf && method !== 'GET') headers[csrf.headerName] = csrf.token;
    if (data && !(data instanceof FormData)) headers['Content-Type'] = 'application/json';
    const response = await fetch(base + url, {method, headers, body: data ? data instanceof FormData ? data : JSON.stringify(data) : undefined});
    const session = response.headers.getSetCookie().find(c => c.startsWith('JSESSIONID='));
    if (session) cookie = session.split(';')[0];
    const body = await response.json();
    assert.equal(response.status, expected, `${method} ${url}: ${JSON.stringify(body)}`);
    if (expected === 200) assert.equal(body.success, true, `${method} ${url}: ${body.message}`);
    checks.push(`${method} ${url.split('?')[0]} → ${expected}`);
    return body;
  };
}
